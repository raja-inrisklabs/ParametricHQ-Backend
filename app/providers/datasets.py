def get_dataset(dataset_id: str) -> Dict[str, Any]:
    key = (dataset_id or "").strip()
    if key not in DATASETS:
        known = ", ".join(DATASETS)
        raise KeyError(f"Unknown dataset '{dataset_id}'. Available: {known}")
    return DATASETS[key]


def list_dataset_variables(dataset_id: str) -> List[Dict[str, str]]:
    item = get_dataset(dataset_id)
    units = item["units"]
    rows = []
    for name in item.get("hourly_variables") or item["variables"]:
        rows.append({
            "name": name,
            "label": name.replace("_", " "),
            "unit": units.get(name, ""),
            "kind": "hourly",
        })
    return rows


def list_datasets(provider_id: str | None = None) -> List[Dict[str, Any]]:
    rows = []
    for item in DATASETS.values():
        if provider_id and item["provider_id"] != provider_id:
            continue
        rows.append(
            {
                "id": item["id"],
                "provider_id": item["provider_id"],
                "name": item["name"],
                "description": item["description"],
                "frequency": item["frequency"],
                "resolution": item["resolution"],
                "variable_count": len(item.get("hourly_variables") or item["variables"]),
            }
        )
    return rows
